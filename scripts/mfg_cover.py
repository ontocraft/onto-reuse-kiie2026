def main() -> None:
    if not SCHEMA.exists():
        print(f"스키마가 없다: {SCHEMA}")
        sys.exit(1)
    d = json.loads(SCHEMA.read_text(encoding="utf-8"))
    ext = d["IOF 밖에서 가져온 것"]
    names = ({c["이름"] for c in d["클래스"]} | {r["이름"] for r in d["관계"]}
             | {c["이름"] for c in ext["클래스"]} | {r["이름"] for r in ext["관계"]})

    print(f"스키마 요소 {len(names)} · 역량 질문 {len(NEED)}")
    print("⚠️ 아래는 요구 요소의 대응이다. 질의 실행이 아니다. 인스턴스는 없다.\n")
    cnt: Counter = Counter()
    used: set[str] = set()
    missing_ref: list[tuple[str, str]] = []
    for q, (need, st, memo) in NEED.items():
        cnt[st] += 1
        for n in need:
            if n in names:
                used.add(n)
            else:
                missing_ref.append((q, n))
        mark = {"답함": "○", "부분": "△", "못함": "✕"}[st]  # 값은 그대로 두고 표기만
        print(f"{mark} {q:<28}{memo}")

    tot = len(NEED)
    print(f"\n요구 요소 대응 {cnt['답함']} · 부분 {cnt['부분']} · 대응 없음 {cnt['못함']}"
          f"   ({cnt['답함']/tot:.0%} · {cnt['부분']/tot:.0%} · {cnt['못함']/tot:.0%})")

    if missing_ref:
        print("\n⚠️ 배정에 적었으나 스키마에 없는 이름")
        for q, n in missing_ref:
            print(f"   {q}: {n}")

    # 배정에 이름이 적히지 않아도 쓰이는 것이 있습니다. 쓰인 관계의 양 끝은
    # 그 질문에 답하려면 반드시 거쳐야 하는 클래스입니다. 직접 세기만 하면
    # 그것을 쓰이지 않는 것으로 잘못 셉니다. 2026-09-30 에 QIF 를 넣고 발견했습니다.
    ends: dict[str, tuple[str, str]] = {
        r["이름"]: (r["출발"], r["도착"])
        for r in list(d["관계"]) + list(ext["관계"])
    }
    reached = set(used)
    for r in used & set(ends):
        reached.update(ends[r])

    direct = sorted(names - used)
    never = sorted(names - reached)
    print(f"\n쓰이지 않는 요소 — 두 가지로 셉니다")
    print(f"  배정에 이름이 적힌 것만 센다     {len(direct):3d} / {len(names)}"
          f"   (쓰이는 것 {len(names) - len(direct)})")
    print(f"  쓰인 관계의 양 끝까지 센다      {len(never):3d} / {len(names)}"
          f"   (쓰이는 것 {len(names) - len(never)})")
    print("\n뒤의 값이 경고 신호입니다. 앞의 값에는 관계의 끝이라 이름 없이")
    print("쓰이는 것이 섞여 있습니다.\n")
    for n in direct:
        print(f"   {'':2s}{n}" if n in reached else f"   ✕ {n}")
    print("\n✕ 는 관계로도 닿지 않는 것입니다. 쓰이지 않는다고 곧 빼야 하는 것은")
    print("아닙니다. 상위 클래스이거나 아직 질문을 만들지 않았을 수 있습니다.")
    print("**왜 두는지 말할 수 없으면 그때 뺍니다.**")


if __name__ == "__main__":
    main()
